"""Code generators for C/C++ DLL export forwarding and proxy stubs."""

from enum import Enum
from pathlib import Path
from typing import List, Optional, Tuple

from .models import PeArch, PeExportInfo
from .lib_generator import ImportLibGenerator


class GeneratorMode(str, Enum):
    """Output generation strategy."""
    PRAGMA = "pragma"
    DEF = "def"
    TRAMPOLINE = "trampoline"
    MASM = "masm"


class CodeGenerator:
    """Generates C/C++ proxy source code, MASM stubs, .def files, CMakeLists, and build scripts."""

    def __init__(
        self,
        info: PeExportInfo,
        mode: GeneratorMode = GeneratorMode.PRAGMA,
        target_dll: Optional[str] = None,
        enable_logging: bool = True,
        enable_file_log: bool = False,
        hooked_symbols: Optional[List[str]] = None,
        generate_lib: bool = True,
        enable_gcc: bool = False,
        enable_trace: bool = False,
        enable_tls_callback: bool = False,
    ):
        self.info = info
        self.mode = mode
        self.enable_logging = enable_logging
        self.enable_file_log = enable_file_log
        self.hooked_symbols = set(hooked_symbols or [])
        self.generate_lib = generate_lib
        self.enable_gcc = enable_gcc
        self.enable_trace = enable_trace
        self.enable_tls_callback = enable_tls_callback

        # If target DLL is not provided, default to system path: C:\Windows\System32\<dll_name>
        if target_dll:
            self.target_dll = target_dll
        else:
            self.target_dll = f"C:\\Windows\\System32\\{self.info.dll_name}"

    @property
    def target_stem_escaped(self) -> str:
        """Format target DLL path for C++ string literals without .dll extension for link pragmas."""
        p = Path(self.target_dll)
        parent_str = str(p.parent)
        stem = p.stem
        if parent_str in ("", "."):
            raw = stem
        else:
            raw = f"{parent_str}\\{stem}"
        return raw.replace("\\", "\\\\")

    @property
    def target_stem_def(self) -> str:
        """Format target DLL path for module definition (.def) files."""
        p = Path(self.target_dll)
        parent_str = str(p.parent)
        stem = p.stem
        if parent_str in ("", "."):
            return stem
        return f"{parent_str}\\{stem}"

    def generate_pragma_source(self) -> str:
        """Generate dllmain.cpp using MSVC /export linker directives."""
        lines = [
            "// ===========================================================================",
            f"// Forwarding Proxy for {self.info.dll_name} (Architecture: {self.info.arch.value})",
            f"// Generated by dll-forward-gen. Total exports: {self.info.total_count}",
            "// ===========================================================================",
            "#define WIN32_LEAN_AND_MEAN",
            "#include <windows.h>",
            "#include <stdio.h>",
            "",
            "// --- Linker Export Forwarding Directives ---",
        ]

        target_base = self.target_stem_escaped

        for sym in self.info.symbols:
            if sym.is_ordinal_only:
                directive = f'#pragma comment(linker, "/export:{sym.safe_name}={target_base}.#{sym.ordinal},@{sym.ordinal},NONAME")'
            else:
                directive = f'#pragma comment(linker, "/export:{sym.name}={target_base}.{sym.name},@{sym.ordinal}")'
            lines.append(directive)

        lines.extend([
            "",
            "// --- DLL Entrypoint & Instrumentation Lifecycle ---",
            "static void OnProcessAttach(HMODULE hModule) {",
            "    DisableThreadLibraryCalls(hModule);",
        ])

        if self.enable_file_log:
            lines.extend([
                '    FILE* fLog = NULL;',
                '    if (fopen_s(&fLog, "proxy_log.txt", "a") == 0 && fLog) {',
                f'        fprintf(fLog, "[dll-forward-gen] Attached to process: {self.info.dll_name}\\n");',
                '        fclose(fLog);',
                '    }',
            ])

        if self.enable_logging:
            lines.extend([
                f'    OutputDebugStringA("[dll-forward-gen] Initialized proxy for {self.info.dll_name}\\n");',
                '    #if defined(_DEBUG)',
                f'    printf("[dll-forward-gen] Attached to process: {self.info.dll_name}\\n");',
                '    #endif',
            ])

        lines.extend([
            "}",
            "",
            "static void OnProcessDetach() {",
        ])

        if self.enable_logging:
            lines.extend([
                f'    OutputDebugStringA("[dll-forward-gen] Unloaded proxy for {self.info.dll_name}\\n");',
            ])

        lines.extend([
            "}",
            "",
        ])

        if self.enable_tls_callback:
            lines.extend([
                "// --- Early Execution TLS Callback (Executes BEFORE DllMain) ---",
                "static void NTAPI OnProxyTlsCallback(PVOID DllHandle, DWORD Reason, PVOID Reserved) {",
                "    (void)DllHandle; (void)Reserved;",
                "    if (Reason == DLL_PROCESS_ATTACH) {",
                f'        OutputDebugStringA("[dll-forward-gen] TLS Callback triggered for {self.info.dll_name}\\n");',
                "    }",
                "}",
                "",
                "#if defined(_MSC_VER)",
                '    #pragma section(".CRT$XLB", read)',
                '    __declspec(allocate(".CRT$XLB")) const PIMAGE_TLS_CALLBACK g_pProxyTlsCallback = OnProxyTlsCallback;',
                "#elif defined(__GNUC__) || defined(__clang__)",
                '    __attribute__((section(".CRT$XLB"))) const PIMAGE_TLS_CALLBACK g_pProxyTlsCallback = OnProxyTlsCallback;',
                "#endif",
                "",
            ])

        lines.extend([
            "BOOL APIENTRY DllMain(HMODULE hModule, DWORD ul_reason_for_call, LPVOID lpReserved) {",
            "    (void)lpReserved;",
            "    switch (ul_reason_for_call) {",
            "    case DLL_PROCESS_ATTACH:",
            "        OnProcessAttach(hModule);",
            "        break;",
            "    case DLL_PROCESS_DETACH:",
            "        OnProcessDetach();",
            "        break;",
            "    case DLL_THREAD_ATTACH:",
            "    case DLL_THREAD_DETACH:",
            "        break;",
            "    }",
            "    return TRUE;",
            "}",
            "",
        ])

        return "\n".join(lines)

    def generate_header_only_source(self) -> str:
        """Generate a standalone, embeddable C/C++ header (.h) without DllMain."""
        lines = [
            "#pragma once",
            "// ===========================================================================",
            f"// Forwarding Header for {self.info.dll_name} (Architecture: {self.info.arch.value})",
            f"// Generated by dll-forward-gen. Total exports: {self.info.total_count}",
            "// Include this file once in any source file in your project to forward exports.",
            "// ===========================================================================",
            "#define WIN32_LEAN_AND_MEAN",
            "#include <windows.h>",
            "",
            "// --- Linker Export Forwarding Directives ---",
        ]

        target_base = self.target_stem_escaped

        for sym in self.info.symbols:
            if sym.is_ordinal_only:
                directive = f'#pragma comment(linker, "/export:{sym.safe_name}={target_base}.#{sym.ordinal},@{sym.ordinal},NONAME")'
            else:
                directive = f'#pragma comment(linker, "/export:{sym.name}={target_base}.{sym.name},@{sym.ordinal}")'
            lines.append(directive)

        lines.append("")
        return "\n".join(lines)

    def generate_def_file(self) -> str:
        """Generate module definition file (.def) for linker exports."""
        lines = [
            f'; Module Definition File for {self.info.dll_name}',
            f'; Generated by dll-forward-gen. Total exports: {self.info.total_count}',
            f'LIBRARY "{self.info.dll_name}"',
            'EXPORTS',
        ]

        target_base = self.target_stem_def

        for sym in self.info.symbols:
            if sym.is_ordinal_only:
                lines.append(f"    {sym.safe_name}={target_base}.#{sym.ordinal} @{sym.ordinal} NONAME")
            else:
                lines.append(f"    {sym.name}={target_base}.{sym.name} @{sym.ordinal}")

        lines.append("")
        return "\n".join(lines)

    def generate_trampoline_sources(self) -> Tuple[str, str]:
        """Generate proxy.cpp and exports.def for runtime intercepting trampolines."""
        target_escaped_w = self.target_dll.replace("\\", "\\\\")
        cpp_lines = [
            "// ===========================================================================",
            f"// Dynamic Intercepting Trampoline Proxy for {self.info.dll_name}",
            f"// Architecture: {self.info.arch.value} | Total exports: {self.info.total_count}",
            "// ===========================================================================",
            "#define WIN32_LEAN_AND_MEAN",
            "#include <windows.h>",
            "#include <stdio.h>",
            "",
            "// Global handle to real loaded library",
            "static HMODULE g_hRealDll = NULL;",
            "",
            "// Function pointer storage",
        ]

        for sym in self.info.symbols:
            cpp_lines.append(f"static FARPROC g_pfn_{sym.safe_name} = NULL;")

        cpp_lines.extend([
            "",
            "// Real library loader and symbol resolver",
            "static BOOL LoadRealLibrary() {",
            "    if (g_hRealDll != NULL) return TRUE;",
            "",
            f'    const wchar_t* targetPath = L"{target_escaped_w}";',
            "    g_hRealDll = LoadLibraryW(targetPath);",
            "    if (!g_hRealDll) {",
            "        // Fallback: try loading from Windows System Directory directly",
            "        wchar_t sysDir[MAX_PATH];",
            "        if (GetSystemDirectoryW(sysDir, MAX_PATH)) {",
            f'            wchar_t fallbackPath[MAX_PATH];',
            f'            swprintf_s(fallbackPath, MAX_PATH, L"%s\\\\{self.info.dll_name}", sysDir);',
            "            g_hRealDll = LoadLibraryW(fallbackPath);",
            "        }",
            "    }",
            "",
            "    if (!g_hRealDll) {",
            f'        OutputDebugStringA("[FATAL] Failed to load real {self.info.dll_name}\\n");',
            "        return FALSE;",
            "    }",
            "",
            "    // Resolve all target functions",
        ])

        for sym in self.info.symbols:
            if sym.is_ordinal_only:
                lookup_expr = f"MAKEINTRESOURCEA({sym.ordinal})"
            else:
                lookup_expr = f'"{sym.name}"'
            cpp_lines.append(f"    g_pfn_{sym.safe_name} = GetProcAddress(g_hRealDll, {lookup_expr});")

        cpp_lines.extend([
            "",
            "    return TRUE;",
            "}",
            "",
        ])

        if self.enable_trace:
            cpp_lines.extend([
                "#include <atomic>",
                "",
                "struct TraceStat {",
                "    const char* name;",
                "    unsigned int ordinal;",
                "    std::atomic<unsigned long long> call_count;",
                "};",
                "",
                "static TraceStat g_stats[] = {",
            ])
            for sym in self.info.symbols:
                s_name = sym.name if sym.name else f"Ordinal_{sym.ordinal}"
                cpp_lines.append(f'    {{ "{s_name}", {sym.ordinal}, {{0}} }},')
            cpp_lines.extend([
                "};",
                "",
                "static void DumpTraceReport(const char* path) {",
                "    FILE* f = NULL;",
                '    if (fopen_s(&f, path, "w") == 0 && f) {',
                '        fprintf(f, "Ordinal,Name,CallCount\\n");',
                "        size_t count = sizeof(g_stats) / sizeof(g_stats[0]);",
                "        for (size_t i = 0; i < count; ++i) {",
                "            unsigned long long c = g_stats[i].call_count.load(std::memory_order_relaxed);",
                '            fprintf(f, "%u,%s,%llu\\n", g_stats[i].ordinal, g_stats[i].name, c);',
                "        }",
                "        fclose(f);",
                "    }",
                "}",
                "",
            ])

        cpp_lines.extend([
            "// --- Proxy Wrapper Stubs ---",
        ])

        for idx, sym in enumerate(self.info.symbols):
            cpp_lines.extend([
                f'extern "C" void* __stdcall proxy_{sym.safe_name}() {{',
                f'    if (!g_pfn_{sym.safe_name}) LoadRealLibrary();',
            ])
            if self.enable_trace:
                cpp_lines.append(f'    g_stats[{idx}].call_count.fetch_add(1, std::memory_order_relaxed);')
            if self.enable_logging:
                cpp_lines.append(
                    f'    OutputDebugStringA("[PROXY TRACE] Call: {sym.safe_name}\\n");'
                )
            cpp_lines.extend([
                f"    // Dispatch to resolved original function",
                f"    FARPROC pfn = g_pfn_{sym.safe_name};",
                f"    if (!pfn) return NULL;",
                f"    return ((void* (__stdcall*)())pfn)();",
                "}",
                "",
            ])

        detach_logic = [
            "    case DLL_PROCESS_DETACH:",
        ]
        if self.enable_trace:
            detach_logic.append('        DumpTraceReport("proxy_call_trace.csv");')
        detach_logic.extend([
            "        if (g_hRealDll) {",
            "            FreeLibrary(g_hRealDll);",
            "            g_hRealDll = NULL;",
            "        }",
            "        break;",
        ])

        cpp_lines.extend([
            "BOOL APIENTRY DllMain(HMODULE hModule, DWORD ul_reason_for_call, LPVOID lpReserved) {",
            "    (void)lpReserved;",
            "    switch (ul_reason_for_call) {",
            "    case DLL_PROCESS_ATTACH:",
            "        DisableThreadLibraryCalls(hModule);",
            "        LoadRealLibrary();",
            "        break;",
            *detach_logic,
            "    }",
            "    return TRUE;",
            "}",
            "",
        ])

        def_lines = [
            f'; Module Definition File for {self.info.dll_name} Trampoline Proxy',
            f'LIBRARY "{self.info.dll_name}"',
            'EXPORTS',
        ]
        for sym in self.info.symbols:
            if sym.is_ordinal_only:
                def_lines.append(f"    {sym.safe_name}=proxy_{sym.safe_name} @{sym.ordinal} NONAME")
            else:
                def_lines.append(f"    {sym.name}=proxy_{sym.safe_name} @{sym.ordinal}")
        def_lines.append("")

        return "\n".join(cpp_lines), "\n".join(def_lines)

    def generate_masm_sources(self) -> Tuple[str, str, str]:
        """Generate MASM assembly stubs (.asm), loader (dllmain.cpp), and exports.def.
        
        This generates true zero-corruption assembly JMP stubs that preserve 100% of registers,
        stack frames, and calling convention fidelity without compiler prologue/epilogue overhead.
        """
        is_64 = self.info.arch in (PeArch.X64, PeArch.ARM64, PeArch.UNKNOWN)
        ptr_type = "qword" if is_64 else "dword"
        target_escaped_w = self.target_dll.replace("\\", "\\\\")

        unhooked_symbols = [s for s in self.info.symbols if (s.name or s.safe_name) not in self.hooked_symbols]
        hooked_symbols = [s for s in self.info.symbols if (s.name or s.safe_name) in self.hooked_symbols]

        # 1. Generate stubs.asm
        if self.info.arch == PeArch.ARM64:
            asm_lines = [
                "; ===========================================================================",
                f"; ARM64 Assembly JMP Trampoline Stubs for {self.info.dll_name}",
                "; Architecture: ARM64 | Syntax: armasm64",
                "; Zero-overhead, register-preserving forwarding using AAPCS64 IP0 (X16)",
                "; ===========================================================================",
                "    AREA |.text|, CODE, READONLY",
                "    ALIGN 4",
                "",
                "    ; --- External Function Pointer Declarations ---",
            ]
            for sym in unhooked_symbols:
                asm_lines.append(f"    IMPORT g_pfn_{sym.safe_name}")

            asm_lines.extend([
                "",
                "    ; --- Direct Assembly Jump Stubs ---",
            ])

            for sym in unhooked_symbols:
                asm_lines.extend([
                    f"    EXPORT proxy_{sym.safe_name}",
                    f"proxy_{sym.safe_name} PROC",
                    f"    adrp    x16, g_pfn_{sym.safe_name}",
                    f"    ldr     x16, [x16, :lo12:g_pfn_{sym.safe_name}]",
                    f"    br      x16",
                    f"proxy_{sym.safe_name} ENDP",
                    "",
                ])

            asm_lines.extend([
                "    END",
                "",
            ])
        else:
            asm_lines = [
                f"; ===========================================================================",
                f"; MASM Assembly JMP Trampoline Stubs for {self.info.dll_name}",
                f"; Architecture: {self.info.arch.value} | Ptr Size: {ptr_type}",
                f"; Zero-overhead, zero-register corruption assembly forwarding.",
                f"; ===========================================================================",
            ]

            if not is_64:
                asm_lines.extend([
                    ".386",
                    ".model flat, c",
                ])

            asm_lines.extend([
                ".code",
                "",
                "; --- External Function Pointer Declarations ---",
            ])

            for sym in unhooked_symbols:
                asm_lines.append(f"extern g_pfn_{sym.safe_name} : {ptr_type}")

            asm_lines.extend([
                "",
                "; --- Direct Assembly Jump Stubs ---",
            ])

            for sym in unhooked_symbols:
                asm_lines.extend([
                    f"proxy_{sym.safe_name} proc",
                    f"    jmp {ptr_type} ptr [g_pfn_{sym.safe_name}]",
                    f"proxy_{sym.safe_name} endp",
                    "",
                ])

            asm_lines.extend([
                "end",
                "",
            ])

        # 2. Generate dllmain.cpp loader
        cpp_lines = [
            "// ===========================================================================",
            f"// MASM DLL Loader & Function Pointer Binder for {self.info.dll_name}",
            "// ===========================================================================",
            "#define WIN32_LEAN_AND_MEAN",
            "#include <windows.h>",
            "#include <stdio.h>",
            "",
            "// Global handle to real loaded library",
            "static HMODULE g_hRealDll = NULL;",
            "",
            "// Function pointer storage accessed by MASM assembly",
            'extern "C" {',
        ]

        for sym in self.info.symbols:
            cpp_lines.append(f"    FARPROC g_pfn_{sym.safe_name} = NULL;")

        cpp_lines.extend([
            "}",
            "",
        ])

        if hooked_symbols:
            cpp_lines.extend([
                "// --- User Customizable Detour Hooks ---",
            ])
            for sym in hooked_symbols:
                cpp_lines.extend([
                    f'extern "C" void* __stdcall Hook_{sym.safe_name}() {{',
                    f'    OutputDebugStringA("[DETOUR HOOK] Intercepted {sym.safe_name}\\n");',
                    f'    // Call original target function:',
                    f'    FARPROC pfn = g_pfn_{sym.safe_name};',
                    f'    if (!pfn) return NULL;',
                    f'    return ((void* (__stdcall*)())pfn)();',
                    f'}}',
                    "",
                ])

        cpp_lines.extend([
            "// Real library loader and symbol resolver",
            "static BOOL LoadRealLibrary() {",
            "    if (g_hRealDll != NULL) return TRUE;",
            "",
            f'    const wchar_t* targetPath = L"{target_escaped_w}";',
            "    g_hRealDll = LoadLibraryW(targetPath);",
            "    if (!g_hRealDll) {",
            "        wchar_t sysDir[MAX_PATH];",
            "        if (GetSystemDirectoryW(sysDir, MAX_PATH)) {",
            f'            wchar_t fallbackPath[MAX_PATH];',
            f'            swprintf_s(fallbackPath, MAX_PATH, L"%s\\\\{self.info.dll_name}", sysDir);',
            "            g_hRealDll = LoadLibraryW(fallbackPath);",
            "        }",
            "    }",
            "",
            "    if (!g_hRealDll) {",
            f'        OutputDebugStringA("[FATAL] Failed to load real {self.info.dll_name}\\n");',
            "        return FALSE;",
            "    }",
            "",
            "    // Bind all original function pointers",
        ])

        for sym in self.info.symbols:
            if sym.is_ordinal_only:
                lookup_expr = f"MAKEINTRESOURCEA({sym.ordinal})"
            else:
                lookup_expr = f'"{sym.name}"'
            cpp_lines.append(f"    g_pfn_{sym.safe_name} = GetProcAddress(g_hRealDll, {lookup_expr});")

        cpp_lines.extend([
            "",
            "    return TRUE;",
            "}",
            "",
            "BOOL APIENTRY DllMain(HMODULE hModule, DWORD ul_reason_for_call, LPVOID lpReserved) {",
            "    (void)lpReserved;",
            "    switch (ul_reason_for_call) {",
            "    case DLL_PROCESS_ATTACH:",
            "        DisableThreadLibraryCalls(hModule);",
            "        LoadRealLibrary();",
        ])

        if self.enable_file_log:
            cpp_lines.extend([
                '        {',
                '            FILE* f = NULL;',
                '            if (fopen_s(&f, "proxy_log.txt", "a") == 0 && f) {',
                f'                fprintf(f, "[MASM PROXY] Attached: {self.info.dll_name}\\n");',
                '                fclose(f);',
                '            }',
                '        }',
            ])

        cpp_lines.extend([
            "        break;",
            "    case DLL_PROCESS_DETACH:",
            "        if (g_hRealDll) {",
            "            FreeLibrary(g_hRealDll);",
            "            g_hRealDll = NULL;",
            "        }",
            "        break;",
            "    }",
            "    return TRUE;",
            "}",
            "",
        ])

        # 3. Generate exports.def
        def_lines = [
            f'; Module Definition File for {self.info.dll_name} MASM Proxy',
            f'LIBRARY "{self.info.dll_name}"',
            'EXPORTS',
        ]
        for sym in self.info.symbols:
            target_symbol = f"Hook_{sym.safe_name}" if (sym.name or sym.safe_name) in self.hooked_symbols else f"proxy_{sym.safe_name}"
            if sym.is_ordinal_only:
                def_lines.append(f"    {sym.safe_name}={target_symbol} @{sym.ordinal} NONAME")
            else:
                def_lines.append(f"    {sym.name}={target_symbol} @{sym.ordinal}")
        def_lines.append("")

        return "\n".join(asm_lines), "\n".join(cpp_lines), "\n".join(def_lines)

    def generate_resource_script(self) -> str:
        """Generate Windows Resource Script (.rc) to preserve DLL version metadata and manifest."""
        stem = Path(self.info.dll_name).stem
        rc_lines = [
            f"// ===========================================================================",
            f"// {stem}.rc - Version resource script for {self.info.dll_name} proxy",
            f"// Generated by dll-forward-gen",
            f"// ===========================================================================",
            "#include <winres.h>",
            "",
            "VS_VERSION_INFO VERSIONINFO",
            "FILEVERSION     1,0,0,1",
            "PRODUCTVERSION  1,0,0,1",
            "FILEFLAGSMASK   VS_FFI_FILEFLAGSMASK",
            "FILEFLAGS       0x0L",
            "FILEOS          VOS_NT_WINDOWS32",
            "FILETYPE        VFT_DLL",
            "FILESUBTYPE     VFT2_UNKNOWN",
            "BEGIN",
            '    BLOCK "StringFileInfo"',
            "    BEGIN",
            '        BLOCK "040904b0"',
            "        BEGIN",
            f'            VALUE "FileDescription", "{stem} Proxy DLL"',
            '            VALUE "FileVersion", "1.0.0.1"',
            f'            VALUE "InternalName", "{self.info.dll_name}"',
            '            VALUE "LegalCopyright", "Copyright (C) 2026"',
            f'            VALUE "OriginalFilename", "{self.info.dll_name}"',
            f'            VALUE "ProductName", "{stem} Proxy"',
            '            VALUE "ProductVersion", "1.0.0.1"',
            "        END",
            "    END",
            '    BLOCK "VarFileInfo"',
            "    BEGIN",
            "        VALUE \"Translation\", 0x0409, 1200",
            "    END",
            "END",
        ]
        if self.info.manifest:
            rc_lines.extend([
                "",
                "// Embedded Application Manifest (copied from target DLL)",
                '2 RT_MANIFEST "app.manifest"',
            ])
        rc_lines.append("")
        return "\n".join(rc_lines)

    def generate_cmake(self, project_name: str) -> str:
        """Generate CMakeLists.txt for compiling the proxy DLL."""
        target_name = Path(self.info.dll_name).stem
        asm_lang = "ASM_MARMASM" if self.info.arch == PeArch.ARM64 else "ASM_MASM"
        return f"""cmake_minimum_required(VERSION 3.20)
project({project_name} LANGUAGES CXX C {asm_lang})

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)

if (MSVC)
    add_compile_options(/W4 /permissive-)
endif()

set(SOURCES dllmain.cpp)
if (EXISTS "${{CMAKE_CURRENT_SOURCE_DIR}}/stubs.asm")
    list(APPEND SOURCES stubs.asm)
endif()
if (EXISTS "${{CMAKE_CURRENT_SOURCE_DIR}}/version.rc")
    list(APPEND SOURCES version.rc)
endif()

add_library({target_name} SHARED ${{SOURCES}})

set_target_properties({target_name} PROPERTIES
    OUTPUT_NAME "{target_name}"
    PREFIX ""
    SUFFIX ".dll"
)

if (EXISTS "${{CMAKE_CURRENT_SOURCE_DIR}}/exports.def")
    set_target_properties({target_name} PROPERTIES
        LINK_FLAGS "/DEF:${{CMAKE_CURRENT_SOURCE_DIR}}/exports.def"
    )
endif()
"""

    def generate_build_bat(self, project_name: str) -> str:
        """Generate build.bat for one-click compilation using MSVC cl.exe and MASM."""
        target_name = Path(self.info.dll_name).stem
        if self.info.arch == PeArch.ARM64:
            asm_tool = "armasm64.exe"
            arch_flag = "ARM64"
        elif self.info.arch in (PeArch.X64, PeArch.UNKNOWN):
            asm_tool = "ml64.exe"
            arch_flag = "X64"
        else:
            asm_tool = "ml.exe"
            arch_flag = "X86"

        return f"""@echo off
setlocal enabledelayedexpansion

echo [dll-forward-gen] Building {self.info.dll_name} proxy ({self.info.arch.value})...

where cl.exe >nul 2>nul
if %ERRORLEVEL% NEQ 0 (
    echo [ERROR] MSVC cl.exe not found in PATH!
    echo Please run this from a Visual Studio Developer Command Prompt ({self.info.arch.value}).
    exit /b 1
)

if not exist build mkdir build
pushd build

set RES_OBJ=
where rc.exe >nul 2>nul
if %ERRORLEVEL% EQU 0 (
    if exist ..\\version.rc (
        rc.exe /nologo /fo version.res ..\\version.rc
        if exist version.res set RES_OBJ=version.res
    )
)

if exist ..\\stubs.asm (
    echo [dll-forward-gen] Assembling stubs.asm with {asm_tool}...
    {asm_tool} /c /nologo /Fo:stubs.obj ..\\stubs.asm
    if %ERRORLEVEL% NEQ 0 (
        echo [ERROR] MASM assembly failed!
        popd
        exit /b 1
    )
    cl.exe /nologo /O2 /W4 /LD ..\\dllmain.cpp stubs.obj !RES_OBJ! /DEF:..\\exports.def /Fe:{target_name}.dll /link /MACHINE:{arch_flag}
) else if exist ..\\exports.def (
    cl.exe /nologo /O2 /W4 /LD ..\\dllmain.cpp !RES_OBJ! /DEF:..\\exports.def /Fe:{target_name}.dll /link /MACHINE:{arch_flag}
) else (
    cl.exe /nologo /O2 /W4 /LD ..\\dllmain.cpp !RES_OBJ! /Fe:{target_name}.dll /link /MACHINE:{arch_flag}
)

if %ERRORLEVEL% EQU 0 (
    echo [SUCCESS] Built {target_name}.dll successfully!
    echo Output: %CD%\\{target_name}.dll
) else (
    echo [ERROR] Compilation failed!
)

popd
endlocal
"""

    def generate_gas_source(self) -> str:
        """Generate GNU Assembler (GAS) stubs for MinGW-w64 and Clang."""
        unhooked_symbols = [s for s in self.info.symbols if (s.name or s.safe_name) not in self.hooked_symbols]

        if self.info.arch == PeArch.ARM64:
            lines = [
                "// ===========================================================================",
                f"// ARM64 GNU Assembler Jump Stubs for {self.info.dll_name}",
                "// Generated by dll-forward-gen (MinGW/Clang)",
                "// ===========================================================================",
                ".text",
                ".align 2",
                "",
            ]
            for sym in unhooked_symbols:
                lines.append(f".extern g_pfn_{sym.safe_name}")

            lines.append("")
            for sym in unhooked_symbols:
                lines.extend([
                    f".globl proxy_{sym.safe_name}",
                    f"proxy_{sym.safe_name}:",
                    f"    adrp x16, g_pfn_{sym.safe_name}",
                    f"    ldr  x16, [x16, :lo12:g_pfn_{sym.safe_name}]",
                    f"    br   x16",
                    "",
                ])
            return "\n".join(lines)

        elif self.info.arch in (PeArch.X64, PeArch.UNKNOWN):
            lines = [
                "# ===========================================================================",
                f"# x64 GNU Assembler Jump Stubs for {self.info.dll_name}",
                "# Generated by dll-forward-gen (MinGW/Clang)",
                "# ===========================================================================",
                ".intel_syntax noprefix",
                ".text",
                "",
            ]
            for sym in unhooked_symbols:
                lines.append(f".extern g_pfn_{sym.safe_name}")

            lines.append("")
            for sym in unhooked_symbols:
                lines.extend([
                    f".globl proxy_{sym.safe_name}",
                    f"proxy_{sym.safe_name}:",
                    f"    jmp qword ptr [rip + g_pfn_{sym.safe_name}]",
                    "",
                ])
            return "\n".join(lines)

        else:  # x86
            lines = [
                "# ===========================================================================",
                f"# x86 GNU Assembler Jump Stubs for {self.info.dll_name}",
                "# Generated by dll-forward-gen (MinGW/Clang)",
                "# ===========================================================================",
                ".intel_syntax noprefix",
                ".text",
                "",
            ]
            for sym in unhooked_symbols:
                lines.append(f".extern _g_pfn_{sym.safe_name}")

            lines.append("")
            for sym in unhooked_symbols:
                lines.extend([
                    f".globl _proxy_{sym.safe_name}",
                    f"_proxy_{sym.safe_name}:",
                    f"    jmp dword ptr [_g_pfn_{sym.safe_name}]",
                    "",
                ])
            return "\n".join(lines)

    def generate_makefile(self, project_name: str) -> str:
        """Generate Makefile for MinGW-w64 make or mingw32-make."""
        stem = Path(self.info.dll_name).stem
        has_asm = self.mode == GeneratorMode.MASM
        has_def = self.mode in (GeneratorMode.DEF, GeneratorMode.TRAMPOLINE, GeneratorMode.MASM)

        objs = ["dllmain.o"]
        if has_asm:
            objs.append("stubs.o")
        objs.append("version.res")

        objs_str = " ".join(objs)
        def_flag = "-Wl,--kill-at,exports.def" if has_def else ""

        asm_rule = """stubs.o: stubs.s
	$(CC) -c stubs.s -o stubs.o
""" if has_asm else ""

        return f"""# Makefile for {self.info.dll_name} proxy (MinGW-w64 / Clang)
# Generated by dll-forward-gen

CC ?= gcc
CXX ?= g++
RC ?= windres
TARGET = {stem}.dll

CFLAGS ?= -O2 -Wall
CXXFLAGS ?= -O2 -Wall -std=c++20
LDFLAGS ?= -shared {def_flag}

all: $(TARGET)

{asm_rule}version.res: version.rc
	$(RC) -i version.rc -o version.res

dllmain.o: dllmain.cpp
	$(CXX) $(CXXFLAGS) -c dllmain.cpp -o dllmain.o

$(TARGET): {objs_str}
	$(CXX) $(CXXFLAGS) -shared -o $(TARGET) {objs_str} $(LDFLAGS)

clean:
	rm -f $(TARGET) *.o *.res
"""

    def generate_build_gcc_bat(self, project_name: str) -> str:
        """Generate build_gcc.bat for compiling with MinGW GCC."""
        stem = Path(self.info.dll_name).stem
        has_asm = self.mode == GeneratorMode.MASM
        has_def = self.mode in (GeneratorMode.DEF, GeneratorMode.TRAMPOLINE, GeneratorMode.MASM)

        return f"""@echo off
setlocal enabledelayedexpansion

echo [dll-forward-gen] Building {self.info.dll_name} proxy with MinGW GCC ({self.info.arch.value})...

where gcc >nul 2>nul
if %ERRORLEVEL% NEQ 0 (
    echo [ERROR] MinGW gcc.exe not found in PATH!
    echo Please install MinGW-w64 or add gcc to your system PATH.
    exit /b 1
)

if not exist build mkdir build
pushd build

set RES_OBJ=
where windres >nul 2>nul
if %ERRORLEVEL% EQU 0 (
    if exist ..\\version.rc (
        windres -i ..\\version.rc -o version.res
        if exist version.res set RES_OBJ=version.res
    )
)

{"if exist ..\\stubs.s gcc -c ..\\stubs.s -o stubs.o" if has_asm else ""}
{"g++ -O2 -std=c++20 -shared -o " + stem + ".dll ..\\dllmain.cpp " + ("stubs.o " if has_asm else "") + "!RES_OBJ! -Wl,--kill-at,..\\exports.def" if has_def else "g++ -O2 -std=c++20 -shared -o " + stem + ".dll ..\\dllmain.cpp !RES_OBJ!"}

if %ERRORLEVEL% EQU 0 (
    echo [SUCCESS] Built {stem}.dll successfully with MinGW GCC!
    echo Output: %CD%\\{stem}.dll
) else (
    echo [ERROR] GCC compilation failed!
)

popd
endlocal
"""

    def emit_project(self, out_dir: Path) -> List[Path]:
        """Emit all generated project files into the destination directory."""
        out_dir.mkdir(parents=True, exist_ok=True)
        created: List[Path] = []
        project_name = Path(self.info.dll_name).stem + "_proxy"

        if self.mode == GeneratorMode.PRAGMA:
            src = self.generate_pragma_source()
            main_path = out_dir / "dllmain.cpp"
            main_path.write_text(src, encoding="utf-8")
            created.append(main_path)

        elif self.mode == GeneratorMode.DEF:
            def_src = self.generate_def_file()
            def_path = out_dir / "exports.def"
            def_path.write_text(def_src, encoding="utf-8")
            created.append(def_path)

            src = self.generate_pragma_source()
            main_path = out_dir / "dllmain.cpp"
            main_path.write_text(src, encoding="utf-8")
            created.append(main_path)

        elif self.mode == GeneratorMode.TRAMPOLINE:
            cpp_src, def_src = self.generate_trampoline_sources()
            main_path = out_dir / "dllmain.cpp"
            main_path.write_text(cpp_src, encoding="utf-8")
            created.append(main_path)

            def_path = out_dir / "exports.def"
            def_path.write_text(def_src, encoding="utf-8")
            created.append(def_path)

        elif self.mode == GeneratorMode.MASM:
            asm_src, cpp_src, def_src = self.generate_masm_sources()
            asm_path = out_dir / "stubs.asm"
            asm_path.write_text(asm_src, encoding="utf-8")
            created.append(asm_path)

            main_path = out_dir / "dllmain.cpp"
            main_path.write_text(cpp_src, encoding="utf-8")
            created.append(main_path)

            def_path = out_dir / "exports.def"
            def_path.write_text(def_src, encoding="utf-8")
            created.append(def_path)

        # Scaffolding: CMakeLists.txt and build.bat
        cmake_path = out_dir / "CMakeLists.txt"
        cmake_path.write_text(self.generate_cmake(project_name), encoding="utf-8")
        created.append(cmake_path)

        bat_path = out_dir / "build.bat"
        bat_path.write_text(self.generate_build_bat(project_name), encoding="utf-8")
        created.append(bat_path)

        # Version Resource Script (.rc)
        rc_path = out_dir / "version.rc"
        rc_path.write_text(self.generate_resource_script(), encoding="utf-8")
        created.append(rc_path)

        # Embedded Manifest (app.manifest) if present in original DLL
        if self.info.manifest:
            manifest_path = out_dir / "app.manifest"
            manifest_path.write_text(self.info.manifest, encoding="utf-8")
            created.append(manifest_path)

        # COFF Import Library (.lib)
        if self.generate_lib:
            lib_stem = Path(self.info.dll_name).stem
            lib_path = out_dir / f"{lib_stem}.lib"
            lib_gen = ImportLibGenerator(self.info)
            lib_gen.write_lib(lib_path)
            created.append(lib_path)

        # MinGW / GCC / Clang universal build scaffolding
        if self.enable_gcc:
            if self.mode == GeneratorMode.MASM:
                gas_path = out_dir / "stubs.s"
                gas_path.write_text(self.generate_gas_source(), encoding="utf-8")
                created.append(gas_path)

            makefile_path = out_dir / "Makefile"
            makefile_path.write_text(self.generate_makefile(project_name), encoding="utf-8")
            created.append(makefile_path)

            gcc_bat_path = out_dir / "build_gcc.bat"
            gcc_bat_path.write_text(self.generate_build_gcc_bat(project_name), encoding="utf-8")
            created.append(gcc_bat_path)

        return created
