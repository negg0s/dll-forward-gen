"""Code generators for C/C++ DLL export forwarding and proxy stubs."""

from enum import Enum
from pathlib import Path
from typing import List, Optional, Tuple

from .models import PeArch, PeExportInfo


class GeneratorMode(str, Enum):
    """Output generation strategy."""
    PRAGMA = "pragma"
    DEF = "def"
    TRAMPOLINE = "trampoline"


class CodeGenerator:
    """Generates C/C++ proxy source code, .def files, CMakeLists, and build scripts."""

    def __init__(
        self,
        info: PeExportInfo,
        mode: GeneratorMode = GeneratorMode.PRAGMA,
        target_dll: Optional[str] = None,
        enable_logging: bool = True,
    ):
        self.info = info
        self.mode = mode
        self.enable_logging = enable_logging

        # If target DLL is not provided, default to system path: C:\Windows\System32\<dll_name>
        if target_dll:
            self.target_dll = target_dll
        else:
            self.target_dll = f"C:\\Windows\\System32\\{self.info.dll_name}"

    @property
    def target_stem_escaped(self) -> str:
        """Format target DLL path for C++ string literals without .dll extension for link pragmas."""
        p = Path(self.target_dll)
        # MSVC pragma /export expects the path or module without the .dll extension
        parent_str = str(p.parent)
        stem = p.stem
        if parent_str in ("", "."):
            raw = stem
        else:
            raw = f"{parent_str}\\{stem}"
        return raw.replace("\\", "\\\\")

    @property
    def target_stem_def(self) -> str:
        """Format target DLL path for module definition (.def) files."""
        p = Path(self.target_dll)
        parent_str = str(p.parent)
        stem = p.stem
        if parent_str in ("", "."):
            return stem
        return f"{parent_str}\\{stem}"

    def generate_pragma_source(self) -> str:
        """Generate dllmain.cpp using MSVC /export linker directives."""
        lines = [
            "// ===========================================================================",
            f"// Forwarding Proxy for {self.info.dll_name} (Architecture: {self.info.arch.value})",
            f"// Generated by dll-forward-gen. Total exports: {self.info.total_count}",
            "// ===========================================================================",
            "#define WIN32_LEAN_AND_MEAN",
            "#include <windows.h>",
            "#include <stdio.h>",
            "",
            "// --- Linker Export Forwarding Directives ---",
        ]

        target_base = self.target_stem_escaped

        for sym in self.info.symbols:
            if sym.is_ordinal_only:
                # Ordinal-only export directive
                directive = f'#pragma comment(linker, "/export:{sym.safe_name}={target_base}.#{sym.ordinal},@{sym.ordinal},NONAME")'
            else:
                directive = f'#pragma comment(linker, "/export:{sym.name}={target_base}.{sym.name},@{sym.ordinal}")'
            lines.append(directive)

        lines.extend([
            "",
            "// --- DLL Entrypoint & Instrumentation Lifecycle ---",
            "static void OnProcessAttach(HMODULE hModule) {",
            "    DisableThreadLibraryCalls(hModule);",
        ])

        if self.enable_logging:
            lines.extend([
                f'    OutputDebugStringA("[dll-forward-gen] Initialized proxy for {self.info.dll_name}\\n");',
                '    #if defined(_DEBUG)',
                f'    printf("[dll-forward-gen] Attached to process: {self.info.dll_name}\\n");',
                '    #endif',
            ])

        lines.extend([
            "}",
            "",
            "static void OnProcessDetach() {",
        ])

        if self.enable_logging:
            lines.extend([
                f'    OutputDebugStringA("[dll-forward-gen] Unloaded proxy for {self.info.dll_name}\\n");',
            ])

        lines.extend([
            "}",
            "",
            "BOOL APIENTRY DllMain(HMODULE hModule, DWORD ul_reason_for_call, LPVOID lpReserved) {",
            "    (void)lpReserved;",
            "    switch (ul_reason_for_call) {",
            "    case DLL_PROCESS_ATTACH:",
            "        OnProcessAttach(hModule);",
            "        break;",
            "    case DLL_PROCESS_DETACH:",
            "        OnProcessDetach();",
            "        break;",
            "    case DLL_THREAD_ATTACH:",
            "    case DLL_THREAD_DETACH:",
            "        break;",
            "    }",
            "    return TRUE;",
            "}",
            "",
        ])

        return "\n".join(lines)

    def generate_def_file(self) -> str:
        """Generate module definition file (.def) for linker exports."""
        lines = [
            f'; Module Definition File for {self.info.dll_name}',
            f'; Generated by dll-forward-gen. Total exports: {self.info.total_count}',
            f'LIBRARY "{self.info.dll_name}"',
            'EXPORTS',
        ]

        target_base = self.target_stem_def

        for sym in self.info.symbols:
            if sym.is_ordinal_only:
                lines.append(f"    {sym.safe_name}={target_base}.#{sym.ordinal} @{sym.ordinal} NONAME")
            else:
                lines.append(f"    {sym.name}={target_base}.{sym.name} @{sym.ordinal}")

        lines.append("")
        return "\n".join(lines)

    def generate_trampoline_sources(self) -> Tuple[str, str]:
        """Generate proxy.cpp and exports.def for runtime intercepting trampolines."""
        cpp_lines = [
            "// ===========================================================================",
            f"// Dynamic Intercepting Trampoline Proxy for {self.info.dll_name}",
            f"// Architecture: {self.info.arch.value} | Total exports: {self.info.total_count}",
            "// ===========================================================================",
            "#define WIN32_LEAN_AND_MEAN",
            "#include <windows.h>",
            "#include <stdio.h>",
            "",
            "// Global handle to real loaded library",
            "static HMODULE g_hRealDll = NULL;",
            "",
            "// Function pointer storage",
        ]

        for sym in self.info.symbols:
            cpp_lines.append(f"static FARPROC g_pfn_{sym.safe_name} = NULL;")

        target_escaped_w = self.target_dll.replace("\\", "\\\\")
        cpp_lines.extend([
            "",
            "// Real library loader and symbol resolver",
            "static BOOL LoadRealLibrary() {",
            "    if (g_hRealDll != NULL) return TRUE;",
            "",
            f'    const wchar_t* targetPath = L"{target_escaped_w}";',
            "    g_hRealDll = LoadLibraryW(targetPath);",
            "    if (!g_hRealDll) {",
            "        // Fallback: try loading from Windows System Directory directly",
            "        wchar_t sysDir[MAX_PATH];",
            "        if (GetSystemDirectoryW(sysDir, MAX_PATH)) {",
            f'            wchar_t fallbackPath[MAX_PATH];',
            f'            swprintf_s(fallbackPath, MAX_PATH, L"%s\\\\{self.info.dll_name}", sysDir);',
            "            g_hRealDll = LoadLibraryW(fallbackPath);",
            "        }",
            "    }",
            "",
            "    if (!g_hRealDll) {",
            f'        OutputDebugStringA("[FATAL] Failed to load real {self.info.dll_name}\\n");',
            "        return FALSE;",
            "    }",
            "",
            "    // Resolve all target functions",
        ])

        for sym in self.info.symbols:
            if sym.is_ordinal_only:
                lookup_expr = f"MAKEINTRESOURCEA({sym.ordinal})"
            else:
                lookup_expr = f'"{sym.name}"'
            cpp_lines.append(f"    g_pfn_{sym.safe_name} = GetProcAddress(g_hRealDll, {lookup_expr});")

        cpp_lines.extend([
            "",
            "    return TRUE;",
            "}",
            "",
            "// --- Proxy Wrapper Stubs ---",
        ])

        for sym in self.info.symbols:
            cpp_lines.extend([
                f'extern "C" void* __stdcall proxy_{sym.safe_name}() {{',
                f'    if (!g_pfn_{sym.safe_name}) LoadRealLibrary();',
            ])
            if self.enable_logging:
                cpp_lines.append(
                    f'    OutputDebugStringA("[PROXY TRACE] Call: {sym.safe_name}\\n");'
                )
            cpp_lines.extend([
                f"    // Dispatch to resolved original function",
                f"    FARPROC pfn = g_pfn_{sym.safe_name};",
                f"    if (!pfn) return NULL;",
                f"    return ((void* (__stdcall*)())pfn)();",
                "}",
                "",
            ])

        cpp_lines.extend([
            "BOOL APIENTRY DllMain(HMODULE hModule, DWORD ul_reason_for_call, LPVOID lpReserved) {",
            "    (void)lpReserved;",
            "    switch (ul_reason_for_call) {",
            "    case DLL_PROCESS_ATTACH:",
            "        DisableThreadLibraryCalls(hModule);",
            "        LoadRealLibrary();",
            "        break;",
            "    case DLL_PROCESS_DETACH:",
            "        if (g_hRealDll) {",
            "            FreeLibrary(g_hRealDll);",
            "            g_hRealDll = NULL;",
            "        }",
            "        break;",
            "    }",
            "    return TRUE;",
            "}",
            "",
        ])

        # Generate DEF file mapping original names to proxy_ stubs
        def_lines = [
            f'; Module Definition File for {self.info.dll_name} Trampoline Proxy',
            f'LIBRARY "{self.info.dll_name}"',
            'EXPORTS',
        ]
        for sym in self.info.symbols:
            if sym.is_ordinal_only:
                def_lines.append(f"    {sym.safe_name}=proxy_{sym.safe_name} @{sym.ordinal} NONAME")
            else:
                def_lines.append(f"    {sym.name}=proxy_{sym.safe_name} @{sym.ordinal}")
        def_lines.append("")

        return "\n".join(cpp_lines), "\n".join(def_lines)

    def generate_cmake(self, project_name: str) -> str:
        """Generate CMakeLists.txt for compiling the proxy DLL."""
        target_name = Path(self.info.dll_name).stem
        return f"""cmake_minimum_required(VERSION 3.20)
project({project_name} LANGUAGES CXX C)

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)

if (MSVC)
    add_compile_options(/W4 /permissive-)
endif()

add_library({target_name} SHARED
    dllmain.cpp
)

set_target_properties({target_name} PROPERTIES
    OUTPUT_NAME "{target_name}"
    PREFIX ""
    SUFFIX ".dll"
)

if (EXISTS "${{CMAKE_CURRENT_SOURCE_DIR}}/exports.def")
    set_target_properties({target_name} PROPERTIES
        LINK_FLAGS "/DEF:${{CMAKE_CURRENT_SOURCE_DIR}}/exports.def"
    )
endif()
"""

    def generate_build_bat(self, project_name: str) -> str:
        """Generate build.bat for one-click compilation using MSVC cl.exe."""
        target_name = Path(self.info.dll_name).stem
        return f"""@echo off
setlocal enabledelayedexpansion

echo [dll-forward-gen] Building {self.info.dll_name} proxy ({self.info.arch.value})...

where cl.exe >nul 2>nul
if %ERRORLEVEL% NEQ 0 (
    echo [ERROR] MSVC cl.exe not found in PATH!
    echo Please run this from a Visual Studio Developer Command Prompt (x64/x86).
    exit /b 1
)

if not exist build mkdir build
pushd build

if exist ..\\exports.def (
    cl.exe /nologo /O2 /W4 /LD ..\\dllmain.cpp /DEF:..\\exports.def /Fe:{target_name}.dll /link /MACHINE:{self.info.arch.value.upper()}
) else (
    cl.exe /nologo /O2 /W4 /LD ..\\dllmain.cpp /Fe:{target_name}.dll /link /MACHINE:{self.info.arch.value.upper()}
)

if %ERRORLEVEL% EQU 0 (
    echo [SUCCESS] Built {target_name}.dll successfully!
    echo Output: %CD%\\{target_name}.dll
) else (
    echo [ERROR] Compilation failed!
)

popd
endlocal
"""

    def emit_project(self, out_dir: Path) -> List[Path]:
        """Emit all generated project files into the destination directory."""
        out_dir.mkdir(parents=True, exist_ok=True)
        created: List[Path] = []
        project_name = Path(self.info.dll_name).stem + "_proxy"

        if self.mode == GeneratorMode.PRAGMA:
            src = self.generate_pragma_source()
            main_path = out_dir / "dllmain.cpp"
            main_path.write_text(src, encoding="utf-8")
            created.append(main_path)

        elif self.mode == GeneratorMode.DEF:
            def_src = self.generate_def_file()
            def_path = out_dir / "exports.def"
            def_path.write_text(def_src, encoding="utf-8")
            created.append(def_path)

            src = self.generate_pragma_source()
            main_path = out_dir / "dllmain.cpp"
            main_path.write_text(src, encoding="utf-8")
            created.append(main_path)

        elif self.mode == GeneratorMode.TRAMPOLINE:
            cpp_src, def_src = self.generate_trampoline_sources()
            main_path = out_dir / "dllmain.cpp"
            main_path.write_text(cpp_src, encoding="utf-8")
            created.append(main_path)

            def_path = out_dir / "exports.def"
            def_path.write_text(def_src, encoding="utf-8")
            created.append(def_path)

        # Scaffolding: CMakeLists.txt and build.bat
        cmake_path = out_dir / "CMakeLists.txt"
        cmake_path.write_text(self.generate_cmake(project_name), encoding="utf-8")
        created.append(cmake_path)

        bat_path = out_dir / "build.bat"
        bat_path.write_text(self.generate_build_bat(project_name), encoding="utf-8")
        created.append(bat_path)

        return created
